// Metro config for the Expo web/native UI.
//
// In development the browser talks to Metro (:8081) and the real API lives on the local Express
// server (:5174). The API is cookie-authenticated and guarded by requireSameOrigin, which compares
// the Origin header with the Host header — so /api is forwarded with the Host header left alone
// (unlike a changeOrigin proxy), keeping Origin and Host in agreement.
const http = require("node:http");
const fs = require("node:fs");
const path = require("node:path");
const { getDefaultConfig } = require("expo/metro-config");
const { MODULES, fileAlias } = require("./mobile-server/aliases.cjs");

const API_PORT = Number(process.env.API_PORT || 5174);
const config = getDefaultConfig(__dirname);

// The phone hosts its own server by running the real server/ code inside the app. That code
// imports Node-only modules (express, node:sqlite, node:crypto, ...), so on native builds those
// imports -- and only those made from server/ -- are swapped for the shims in mobile-server/shims.
// Web builds never import server/, so they are untouched.
// assets/web-ui.zip is generated by `npm run pack:web-ui`. Until it exists, write an empty zip so
// the app still bundles (the phone then simply has no web UI to hand to students).
const WEB_UI_ZIP = path.join(__dirname, "assets", "web-ui.zip");
if (!fs.existsSync(WEB_UI_ZIP)) {
  fs.mkdirSync(path.dirname(WEB_UI_ZIP), { recursive: true });
  fs.writeFileSync(WEB_UI_ZIP, Buffer.from([0x50, 0x4b, 0x05, 0x06, ...new Array(18).fill(0)]));
}

const SERVER_DIR = path.join(__dirname, "server") + path.sep;
const defaultResolve = config.resolver.resolveRequest;
config.resolver = {
  ...config.resolver,
  // The web UI is bundled into the app as a zip and served to students from memory.
  assetExts: [...config.resolver.assetExts, "zip"],
  resolveRequest: (context, moduleName, platform) => {
    if (platform !== "web") {
      const fromServer = (context.originModulePath || "").startsWith(SERVER_DIR);
      if (fromServer && MODULES[moduleName]) return { type: "sourceFile", filePath: MODULES[moduleName] };
      const resolved = (defaultResolve || context.resolveRequest)(context, moduleName, platform);
      if (resolved?.type === "sourceFile") {
        const alias = fileAlias(resolved.filePath);
        if (alias) return { type: "sourceFile", filePath: alias };
      }
      return resolved;
    }
    return (defaultResolve || context.resolveRequest)(context, moduleName, platform);
  },
};

config.server = {
  ...config.server,
  enhanceMiddleware: (metroMiddleware) => (req, res, next) => {
    if (!req.url.startsWith("/api")) return metroMiddleware(req, res, next);
    const upstream = http.request(
      { host: "127.0.0.1", port: API_PORT, path: req.url, method: req.method, headers: req.headers },
      (up) => {
        res.writeHead(up.statusCode || 502, up.headers);
        up.pipe(res);
      }
    );
    upstream.on("error", () => {
      res.statusCode = 502;
      res.end(JSON.stringify({ error: "Local server is not running." }));
    });
    req.pipe(upstream);
  },
};

module.exports = config;
